"""
Generate full-text software engineering resumes from structured synthetic resume records.

This script reads a CSV or Parquet file of structured synthetic resumes, sends each row
to an LLM, and writes a CSV/Parquet with generated resume text.

It supports multiple prompt modes so the capstone can compare full-text resumes with
and without age-proxy leakage.

Example:

python src/llm_resume_generation.py \
  --input data/processed/synthetic_resumes_full.parquet \
  --output data/processed/synthetic_resumes_fulltext_sample.csv \
  --mode without_direct_age_proxies \
  --limit 25

Environment:

export OPENAI_API_KEY="..."
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import pandas as pd
from openai import OpenAI


DEFAULT_MODEL = "gpt-4o-mini"
DEFAULT_PROMPT_VERSION = "v2_schema_aware_fulltext_resume_generation"


# ---------------------------------------------------------------------
# Prompt modes
# ---------------------------------------------------------------------

ALWAYS_EXCLUDE_COLUMNS = {
    # Protected/evaluation fields
    "true_age",
    "age",
    "age_group",

    # Labels/outcomes
    "callback",
    "interview",
    "offer",
    "selected",
    "outcome",
    "target",
    "label",

    # Application preference fields, not resume content
    "salary_expectation_usd",
    "willing_to_relocate",
    "remote_only",

    # Anything generated by this script
    "resume_text",
    "llm_model",
    "prompt_version",
    "generated_at",
    "generation_error",
    "generation_mode",
}


MODE_EXCLUDE_COLUMNS = {
    # Includes common real-world age proxies such as graduation_year,
    # estimated_start_year, years_experience_total, and seniority/title.
    # Still excludes true age, age_group, and labels.
    "with_proxies": set(),

    # Removes explicit date proxies, while preserving experience/seniority fields.
    # This matches your current real-world resume strategy pretty closely.
    "without_direct_age_proxies": {
        "graduation_year",
        "estimated_start_year",
        "salary_expectation_usd",
    },

    # More aggressive attempt to suppress age leakage.
    # Keeps skills and role-relevant facts but removes many age/seniority proxies.
    "minimal_proxy": {
        "graduation_year",
        "estimated_start_year",
        "years_experience_total",
        "years_experience_relevant",
        "num_employers",
        "avg_tenure_years",
        "months_since_last_role",
        "num_gaps_over_6mo",
        "management_years",
        "reports_max",
        "legacy_tech_count",
        "modern_tech_count",
        "leadership_signal_score",
        "stability_score",
        "salary_expectation_usd",
    },
}


SYSTEM_PROMPT = """
You convert structured synthetic resume records into realistic plain-text software engineering resumes.

Rules:
- Preserve only the facts provided in the structured input.
- Do not invent employers, titles, schools, degrees, dates, certifications, awards, metrics, locations, database names, project names, or technologies.
- Only include URLs that are explicitly present in the structured input.
- Do not mention age, age group, protected class, demographics, callback labels, interview labels, offer labels, or fairness labels.
- If a GitHub URL or portfolio URL is present, include it exactly as provided.
- Do not create generic numbered credentials such as "Certification 1", "Certification 2", or "Certification 3".
- If only a certification count is provided, describe it as a count; do not invent certification names.
- Do not mention projects unless project details are provided.
- Do not imply age with phrases like "young professional", "recent graduate", "seasoned veteran", "late-career", or "older candidate".
- Do not add graduation years unless they are present in the structured input.
- Do not add employment dates unless they are present in the structured input.
- If a specific employer name, school name, certification name, project name, URL, or database name is missing, omit it entirely.
- Never use placeholder text such as "[Company Name]", "[School Name]", "[GitHub URL]", "[Certification 1]", "not provided", "unspecified", or similar.
- Never include bracketed placeholders of any kind.
- If highest_degree is "None", omit the Education section rather than writing "Highest Degree: None".
- If the structured input contains counts or scores, translate them into resume-like language without exposing internal score names.
- Keep the resume realistic, concise, professional, and ATS-readable.
- Use plain text only.
- Use sections when supported by the input: Summary, Skills, Experience, Education, Certifications, Projects.
- If a field is missing, omit it rather than filling it in.
- Output only the resume text.
""".strip()


